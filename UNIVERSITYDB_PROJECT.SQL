-- QUERY A: RETRIEVE ALL STUDENT DETAILS ALONG WITH THEIR DEPARTMENT NAMES

SELECT S.STUDENTID, S.NAME, S.AGE, S.DEPARTMENTID, D.DEPARTMENTNAME
FROM STUDENTS S
INNER JOIN DEPARTMENTS D
ON S.DEPARTMENTID = D.DEPARTMENTID;

-- QUERY B: FIND STUDENTS ENROLLED IN ARTIFICIAL INTELLIGENCE

SELECT S.NAME
FROM STUDENTS S
INNER JOIN COURSES C
ON S.STUDENTID = C.STUDENTID
WHERE C.COURSENAME = 'ARTIFICIAL INTELLIGENCE';

-- QUERY C: COUNT HOW MANY STUDENTS ARE IN EACH DEPARTMENT

SELECT D.DEPARTMENTNAME, COUNT(S.STUDENTID) AS STUDENTCOUNT
FROM DEPARTMENTS D
LEFT JOIN STUDENTS S
ON D.DEPARTMENTID = S.DEPARTMENTID
GROUP BY D.DEPARTMENTID, D.DEPARTMENTNAME;

-- QUERY D: LIST THE COURSES TAKEN BY ALICE JOHNSON

SELECT C.COURSENAME
FROM STUDENTS S
INNER JOIN COURSES c
ON S.STUDENTID = C.STUDENTID
WHERE S.NAME = 'ALICE JOHNSON';

-- QUERY E: FIND STUDENTS ENROLLED IN MORE THAN ONE COURSE

SELECT S.NAME, COUNT(C.COURSEID) AS COURSECOUNT
FROM STUDENTS S
INNER JOIN COURSES C
ON S.STUDENTID = C.STUDENTID
GROUP BY S.STUDENTID, S.NAME
HAVING COUNT(C.COURSEID) > 1;

-- QUERY F: GET THE AVERAGE AGE OF STUDENTS IN EACH DEPARTMENT

SELECT D.DEPARTMENTNAME, AVG(S.AGE) AS AVERAGEAGE
FROM DEPARTMENTS D
INNER JOIN STUDENTS S
ON D.DEPARTMENTID = S.DEPARTMENTID
GROUP BY D.DEPARTMENTID, D.DEPARTMENTNAME;

-- QUERY G: FIND THE DEPARTMENT WITH THE MOST STUDENTS

SELECT D.DEPARTMENTNAME, COUNT(S.STUDENTID) AS STUDENTCOUNT
FROM DEPARTMENTS D
LEFT JOIN STUDENTS S
ON D.DEPARTMENTID = S.DEPARTMENTID
GROUP BY D.DEPARTMENTID, D.DEPARTMENTNAME
ORDER BY STUDENTCOUNT DESC
LIMIT 1;

-- QUERY H: LIST ALL STUDENTS WHO ARE NOT ENROLLED IN ANY COURSES

SELECT S.STUDENTID, S.NAME
FROM STUDENTS S
LEFT JOIN COURSES C
ON S.STUDENTID = C.STUDENTID
WHERE C.COURSEID IS NULL;

-- QUERY I: RETRIEVE STUDENTS ALONG WITH THE TOTAL NUMBER OF COURSES THEY ARE ENROLLED IN

SELECT S.STUDENTID, S.NAME, COUNT(C.COURSEID) AS TOTALCOURSES
FROM STUDENTS s
LEFT JOIN COURSES c
ON S.STUDENTID = C.STUDENTID
GROUP BY S.STUDENTID, S.NAME;

-- QUERY J: FIND COMPUTER SCIENCE STUDENTS TALING A COURSE WITH 'DATA' IN ITS NAME

SELECT DISTINCT S.NAME, D.DEPARTMENTNAME, C.COURSENAME
FROM STUDENTS S
INNER JOIN DEPARTMENTS D
ON S.DEPARTMENTID = D.DEPARTMENTID
INNER JOIN COURSES C
ON S.STUDENTID = C.STUDENTID
WHERE D.DEPARTMENTNAME = 'COMPUTER SCIENCE'
AND C.COURSENAME LIKE '%DATA%';
