USE WORLD;
-- Q1. DISPLAY THE NAME, CONTINENT, AND POPULATION OF ALL COUNTRIES LOCATED IN ASIA.
SELECT NAME, CONTINENT, POPULATION
FROM COUNTRY
WHERE CONTINENT = 'ASIA';
-- Q2. DISPLAY THE NAME, POPULATION, AND LIFEEXPECTANCY OF ALL COUNTRIES.
-- SORT THE RESULTS BY POPULATION IN DESCENDING ORDER.
SELECT NAME, POPULATION, LIFEEXPECTANCY
FROM COUNTRY
ORDER BY POPULATION DESC;
-- Q3. DISPLAY THE NAME, CONTINENT, AND POPULATION OF COUNTRIES THAT
-- BELONG TO EUROPE AND HAVE A POPULATION GREATER THAN 20,000,000.
-- SORT THE RESULTS ALPHABETICALLY BY COUNTRY NAME.
SELECT NAME, CONTINENT, POPULATION
FROM COUNTRY
WHERE CONTINENT = 'EUROPE'
AND POPULATION > 20000000
ORDER BY NAME;
-- Q4. DISPLAY THE NAME, REGION, AND SURFACEAREA OF COUNTRIES THAT ARE LOCATED
-- IN EITHER NORTH AMERICA OR SOUTH AMERICA.
-- SORT THE RESULTS BY REGION.
SELECT NAME, REGION, SURFACEAREA
FROM COUNTRY
WHERE CONTINENT IN('NORTH AMERICA', 'SOUTH AMERICA')
ORDER BY REGION;
-- Q5. DISPLAY THE NAME, CONTINENT, AND POPULATION OF ALL COUNTRIES
-- THAT ARE NOT LOCATED IN AFRICA.
-- SORT THE RESULTS BY COUNTRY NAME.
SELECT NAME, CONTINENT, POPULATION
FROM COUNTRY
WHERE CONTINENT <> 'AFRICA'
ORDER BY NAME;
-- Q6. DISPLAY THE NAME, POPULATION, AND GOVERNMENTFORM OF COUNTRIES
-- WHOSE POPULATION IS BETWEEN 10,000,000 AND 50,000,000.
-- SORT THE RESULTS BY POPULATION.
SELECT NAME, POPULATION, GOVERNMENTFORM
FROM COUNTRY
WHERE POPULATION BETWEEN 10000000 AND 50000000
ORDER BY POPULATION;
-- Q7. DISPLAY THE NAME, CAPITAL, AND POPULATION OF COUNTRIES WHOSE
-- CONTINENT IS ONE OF THE FOLLOWING: ASIA, EUROPE, OCEANIA.
SELECT NAME, CAPITAL, POPULATION
FROM COUNTRY
WHERE CONTINENT IN ('ASIA', 'EUROPE', 'OCEANIA');
-- Q8. DISPLAY THE NAME, REGION, AND POPULATION OF COUNTRIES
-- WHOSE NAMES START WITH THE LETTER 'A'.
-- SORT THE RESULTS ALPHABETICALLY.
SELECT NAME, REGION POPLATION
FROM COUNTRY
WHERE NAME LIKE 'A%'
ORDER BY NAME;
-- Q9. DISPLAY NAME, CONTINENT, POPULATION, AND LIFEEXPECTANCY OF COUNTRIES
-- THAT ARE IN ASIA OR EUROPE, HAVE A POPULATION GREATER THAN 50,000,000,
-- AND HAVE A LIFE EXPECTANCY GREATER THAN 70.
-- SORT THE RESULTS BY POPULATION IN DESCENDING ORDER.
SELECT NAME, CONTINENT, POPULATION, LIFEEXPECTANCY
FROM COUNTRY
WHERE CONTINENT IN ('ASIA', 'EUROPE')
AND POPULATION > 50000000
AND LIFEEXPECTANCY > 70 
ORDER BY POPULATION DESC;
-- Q10. DISPLAY THE NAME, CONTINENT, POPULATION, AND GOVERNMENTFORM OF COUNTRIES
-- THAT ARE NOT IN AFRICA, HAVE POPULATION BETWEEN 5,000,000 AND 30,000,000,
-- AND WHOSE NAMES CONTAIN THE LETTER 'LAND'.
-- SORT THE RESULTS ALPHABETICALLY.
SELECT NAME, CONTINENT, POPULATION, GOVERNMENTFORM
FROM COUNTRY
WHERE CONTINENT <> 'AFRICA'
AND POPULATION BETWEEN 5000000 AND 30000000
AND NAME LIKE '1%AND%'
ORDER BY NAME;